"""Build the Cloudflare Pages copy of the site into dist/ (run: python3 -I tools/build_cf.py).

Why: the Vercel account was paused on Nov 20, 2026 (Hobby's 10 GB Fast Origin Transfer used up), so the site can also be
served from Cloudflare Pages, whose free plan does not meter bandwidth. Cloudflare publishes the whole output folder, so
this copies only the public files: everything .vercelignore keeps out of the Vercel deployment stays out of dist/ too, plus
the Vercel-only files (api/, vercel.json, package.json). One exclude list for both hosts.

It also writes, from vercel.json, so the two hosts never drift:
  dist/_redirects  the short links (/ig, /tt, /fb) and the app rewrites (/scores -> /, /team/:id -> /, ...)
  dist/_headers    the security headers
and a <dir>.html copy of every <dir>/index.html (/teams, /teams/49ers, /weekly, ...), so Cloudflare serves /teams/49ers
itself instead of redirecting to /teams/49ers/ (our canonical URLs have no trailing slash).

It also writes cf/_meta.json (tools/build_cf_meta.mjs) and the run_worker_first list in wrangler.jsonc, so cf/worker.js gives
app paths their own <head> (what api/page.js did on Vercel). Not on Cloudflare: /api/espn-csv (the page reads
data/espn_assets.json).

Cloudflare Pages settings: build command `python3 tools/build_cf.py`, build output directory `dist`, root directory empty.
"""
import fnmatch
import json
import os
import re
import shutil
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'dist')
EXTRA = ['.git', '.vercel', '.vercelignore', 'node_modules', 'dist', 'api', 'vercel.json', 'package.json',
         'package-lock.json', '.wrangler', 'functions', 'wrangler.toml', 'wrangler.jsonc', 'cf', '.og-cache']


def patterns():
    out = list(EXTRA)
    with open(os.path.join(ROOT, '.vercelignore')) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith('#'):
                out.append(line.strip('/'))
    return out


def ignored(rel, pats):
    parts = rel.split('/')
    for p in pats:
        if '/' in p:
            if fnmatch.fnmatch(rel, p) or rel.startswith(p + '/'):
                return True
        elif any(fnmatch.fnmatch(x, p) for x in parts):
            return True
    return False


def to_cf(path):
    """Vercel path pattern -> Cloudflare: /ig/:path* -> /ig/*, /news/:topic(a|b) -> /news/:topic."""
    path = re.sub(r':(\w+)\*', '*', path)
    return re.sub(r'(:\w+)\([^)]*\)', r'\1', path)


def worker_first(v):
    """wrangler.jsonc's run_worker_first: /api/* plus every app path (the rewrites to "/" in vercel.json), as globs.
    Only these run cf/worker.js; every other request is a static file and never counts as a Worker request."""
    out = ['/api/*']
    for r in v.get('rewrites', []):
        if r.get('has') or r['destination'] != '/':
            continue
        g = re.sub(r':\w+(\([^)]*\))?', '*', r['source'])
        if g not in out:
            out.append(g)
    # a trailing * spans slashes, and wrangler rejects a rule another one already covers (/team/*/* under /team/*)
    return [g for g in out if not any(h != g and h.endswith('/*') and g.startswith(h[:-1]) for h in out)]


def write_worker_first(v):
    p = os.path.join(ROOT, 'wrangler.jsonc')
    with open(p) as f:
        s = f.read()
    line = '    "run_worker_first": ' + json.dumps(worker_first(v)) + ',  // generated by tools/build_cf.py from vercel.json'
    s2, n = re.subn(r'^    "run_worker_first": .*$', line.replace('\\', '\\\\'), s, count=1, flags=re.M)
    if n != 1:
        raise SystemExit('run_worker_first line not found in wrangler.jsonc')
    if s2 != s:
        with open(p, 'w') as f:
            f.write(s2)


def main():
    # cf/_meta.json for the app-path heads (cf/worker.js); needs index.html, so run build.sh first
    subprocess.run(['node', os.path.join(ROOT, 'tools', 'build_cf_meta.mjs')], check=True)
    pats = patterns()
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    n = 0
    for dp, dns, fns in os.walk(ROOT):
        rd = os.path.relpath(dp, ROOT).replace(os.sep, '/')
        rd = '' if rd == '.' else rd
        dns[:] = [d for d in dns if not ignored((rd + '/' + d).lstrip('/'), pats)]
        for fn in fns:
            rel = (rd + '/' + fn).lstrip('/')
            if ignored(rel, pats):
                continue
            dst = os.path.join(OUT, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(os.path.join(ROOT, rel), dst)
            n += 1
            if fn == 'index.html' and rd:
                shutil.copy2(dst, os.path.join(OUT, rd + '.html'))
                n += 1

    with open(os.path.join(ROOT, 'vercel.json')) as f:
        v = json.load(f)
    write_worker_first(v)
    lines = ['# Generated by tools/build_cf.py from vercel.json. Do not edit.']
    for r in v.get('redirects', []):
        if r.get('has'):  # the fan-cap-tracker.vercel.app host redirect: Vercel only
            continue
        src, dst = to_cf(r['source']), r['destination'].replace(':path*', ':splat')
        lines.append(f"{src} {dst} {301 if r.get('permanent') else 302}")
    # App paths (the rewrites to "/") need no rule here: run_worker_first sends them to cf/worker.js, which serves index.html
    # with the page's own head. Cloudflare allows only 100 dynamic rules (with :placeholders or *), so only fixed paths get
    # a trailing-slash redirect (trailingSlash: false on Vercel sent /scores/ to /scores); /team/kc/ and the like reach the
    # Worker anyway, which answers them with the right canonical.
    for r in v.get('rewrites', []):
        if r.get('has') or r['destination'] == '/' or r['destination'].startswith('/api/'):
            continue
        lines.append(f"{to_cf(r['source'])} {r['destination']} 200")
    slash = [f"{r['source']}/ {r['source']} 301" for r in v.get('rewrites', [])
             if not r.get('has') and r['destination'] == '/' and ':' not in r['source']]
    lines[1:1] = list(dict.fromkeys(slash))
    dynamic = [l for l in lines[1:] if ':' in l.split()[0] or '*' in l.split()[0]]
    if len(dynamic) > 100:
        raise SystemExit(f'{len(dynamic)} dynamic _redirects rules; Cloudflare allows 100')
    with open(os.path.join(OUT, '_redirects'), 'w') as f:
        f.write('\n'.join(lines) + '\n')

    hl = ['# Generated by tools/build_cf.py from vercel.json. Do not edit.']
    for h in v.get('headers', []):
        hl.append(h['source'].replace('(.*)', '*'))
        hl += [f"  {x['key']}: {x['value']}" for x in h['headers']]
    with open(os.path.join(OUT, '_headers'), 'w') as f:
        f.write('\n'.join(hl) + '\n')

    leaks = [p for p in ('src.html', 'CLAUDE.md', 'README.md', 'tools', 'data/ledger.csv', 'data/cba.json', '.github')
             if os.path.exists(os.path.join(OUT, p))]
    if leaks:
        raise SystemExit('private files in dist/: ' + ', '.join(leaks))
    print(f'dist/: {n} files, {len(lines) - 1} redirect/rewrite rules')


if __name__ == '__main__':
    main()
