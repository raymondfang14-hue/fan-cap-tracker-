"""Build the Cloudflare Pages copy of the site into dist/ (run: python3 -I tools/build_cf.py).

Why: the Vercel account was paused on Nov 20, 2026 (Hobby's 10 GB Fast Origin Transfer used up), so the site can also be
served from Cloudflare Pages, whose free plan does not meter bandwidth. Cloudflare publishes the whole output folder, so
this copies only the public files: everything .vercelignore keeps out of the Vercel deployment stays out of dist/ too, plus
the Vercel-only files (api/, vercel.json, package.json). One exclude list for both hosts.

It also writes, from vercel.json, so the two hosts never drift:
  dist/_redirects  the short links (/ig, /tt, /fb) and the app rewrites (/scores -> /, /team/:id -> /, ...)
  dist/_headers    the security headers
and a <dir>.html copy of every <dir>/index.html (/teams, /teams/49ers, /weekly, ...), so Cloudflare serves /teams/49ers
itself instead of redirecting to /teams/49ers/ (our canonical URLs have no trailing slash).

Not on Cloudflare (the page falls back for each): the bot meta function api/page.js (crawlers get the generic <head> on app
paths; the static /players, /teams, ... pages are unaffected), /api/og social card images, /api/contracts (the built-in DEALS
show), /api/espn-csv (data/espn_assets.json) and Vercel Web Analytics (GA4 still runs).

Cloudflare Pages settings: build command `python3 tools/build_cf.py`, build output directory `dist`, root directory empty.
"""
import fnmatch
import json
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'dist')
EXTRA = ['.git', '.vercel', '.vercelignore', 'node_modules', 'dist', 'api', 'vercel.json', 'package.json',
         'package-lock.json', '.wrangler', 'functions', 'wrangler.toml']


def patterns():
    out = list(EXTRA)
    with open(os.path.join(ROOT, '.vercelignore')) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith('#'):
                out.append(line.strip('/'))
    return out


def ignored(rel, pats):
    parts = rel.split('/')
    for p in pats:
        if '/' in p:
            if fnmatch.fnmatch(rel, p) or rel.startswith(p + '/'):
                return True
        elif any(fnmatch.fnmatch(x, p) for x in parts):
            return True
    return False


def to_cf(path):
    """Vercel path pattern -> Cloudflare: /ig/:path* -> /ig/*, /news/:topic(a|b) -> /news/:topic."""
    path = re.sub(r':(\w+)\*', '*', path)
    return re.sub(r'(:\w+)\([^)]*\)', r'\1', path)


def main():
    pats = patterns()
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    n = 0
    for dp, dns, fns in os.walk(ROOT):
        rd = os.path.relpath(dp, ROOT).replace(os.sep, '/')
        rd = '' if rd == '.' else rd
        dns[:] = [d for d in dns if not ignored((rd + '/' + d).lstrip('/'), pats)]
        for fn in fns:
            rel = (rd + '/' + fn).lstrip('/')
            if ignored(rel, pats):
                continue
            dst = os.path.join(OUT, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(os.path.join(ROOT, rel), dst)
            n += 1
            if fn == 'index.html' and rd:
                shutil.copy2(dst, os.path.join(OUT, rd + '.html'))
                n += 1

    with open(os.path.join(ROOT, 'vercel.json')) as f:
        v = json.load(f)
    lines = ['# Generated by tools/build_cf.py from vercel.json. Do not edit.']
    for r in v.get('redirects', []):
        if r.get('has'):  # the fan-cap-tracker.vercel.app host redirect: Vercel only
            continue
        src, dst = to_cf(r['source']), r['destination'].replace(':path*', ':splat')
        lines.append(f"{src} {dst} {301 if r.get('permanent') else 302}")
    for r in v.get('rewrites', []):
        if r.get('has') or r['destination'].startswith('/api/'):  # the bot meta function: Vercel only
            continue
        lines.append(f"{to_cf(r['source'])} {r['destination']} 200")
    with open(os.path.join(OUT, '_redirects'), 'w') as f:
        f.write('\n'.join(lines) + '\n')

    hl = ['# Generated by tools/build_cf.py from vercel.json. Do not edit.']
    for h in v.get('headers', []):
        hl.append(h['source'].replace('(.*)', '*'))
        hl += [f"  {x['key']}: {x['value']}" for x in h['headers']]
    with open(os.path.join(OUT, '_headers'), 'w') as f:
        f.write('\n'.join(hl) + '\n')

    leaks = [p for p in ('src.html', 'CLAUDE.md', 'README.md', 'tools', 'data/ledger.csv', 'data/cba.json', '.github')
             if os.path.exists(os.path.join(OUT, p))]
    if leaks:
        raise SystemExit('private files in dist/: ' + ', '.join(leaks))
    print(f'dist/: {n} files, {len(lines) - 1} redirect/rewrite rules')


if __name__ == '__main__':
    main()
